// Phase-four rehearsal on a task-owned database. No response mocks.
const fs=require('node:fs/promises');
const path=require('node:path');
const {createRequire}=require('node:module');
const runtimeRequire=createRequire(path.join(process.env.RUNTIME_NODE_MODULES,'__phase4__.cjs'));
const {chromium}=runtimeRequire('playwright');
const ROOT=path.resolve(__dirname,'..');const QA=path.join(ROOT,'docs/phase4');
const verifyOnly=process.argv.includes('--verify-only');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1600,height:900}});
 const page=await context.newPage();let errors=[],external=[];
 page.setDefaultTimeout(12000);
 page.on('pageerror',e=>errors.push(String(e)));
 context.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:8004'))external.push(r.url());});
 const card=name=>page.locator('section.card').filter({has:page.getByRole('heading',{name,exact:true})});
 async function shot(locator,name){if(verifyOnly)return;await locator.scrollIntoViewIfNeeded();await page.waitForTimeout(350);await locator.screenshot({path:path.join(QA,name+'.png')});}
 await page.goto('http://127.0.0.1:8004/growth');
 await page.getByRole('heading',{name:'四类用户，四条触达路径',exact:true}).waitFor();
 await shot(page.locator('.grid.two').filter({has:page.locator('.persona')}).first(),'personas');
 await page.getByRole('tab',{name:'预算与增长模型',exact:true}).click();
 await page.getByLabel('校园社群预算',{exact:true}).fill('600');
 await page.getByLabel('访问率',{exact:true}).fill('12');
 await page.getByRole('button',{name:'保存参数',exact:true}).click();
 await page.getByRole('status').filter({hasText:'已保存'}).waitFor();
 const baseline=await(await context.request.get('http://127.0.0.1:8004/api/growth/config')).json();
 if(baseline.channels[0].budget!==600||baseline.visit_rate!==.12)throw Error('Baseline reset failed');
 await page.getByLabel('校园社群预算',{exact:true}).fill('900');
 await page.getByLabel('访问率',{exact:true}).fill('20');
 await page.waitForFunction(()=>document.querySelector('.funnel-numbers')?.textContent.includes('2,400'));
 await page.getByRole('button',{name:'保存参数',exact:true}).click();
 await page.getByRole('status').filter({hasText:'已保存'}).waitFor();
 await shot(page.locator('.growth-model'),'growth-demo');
 await page.reload();await page.getByRole('tab',{name:'预算与增长模型',exact:true}).click();
 if(await page.getByLabel('校园社群预算',{exact:true}).inputValue()!=='900')throw Error('Persistence failed');
 await page.getByRole('tab',{name:'实验与执行',exact:true}).click();
 await page.getByRole('button',{name:'计算实验差异',exact:false}).click();
 await shot(card('A/B实验计算器'),'experiment');
 await page.goto('http://127.0.0.1:8004/logistics');
 await page.getByRole('button',{name:'暴雨风险 主走廊降雨增强'}).click();
 await page.getByRole('button',{name:'运行风险分析',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.risk-number')?.textContent.includes('47.15'));
 await shot(card('四类应对策略，逐项对比'),'plans');
 await page.getByRole('button',{name:'生成分析解释',exact:true}).click();
 await page.getByText('规则模式',{exact:true}).last().waitFor();
 await shot(card('分析智能体：有流程，也有记录'),'agent');
 await page.getByRole('button',{name:'运行情景仿真',exact:true}).click();
 await page.getByRole('heading',{name:'逐订单对比',exact:true}).waitFor();
 if(!verifyOnly)await page.screenshot({path:path.join(QA,'simulation.png'),fullPage:true});
 const health=await(await context.request.get('http://127.0.0.1:8004/api/health')).json();
 const config=await(await context.request.get('http://127.0.0.1:8004/api/growth/config')).json();
 await fs.writeFile(path.join(QA,'demo-check.json'),JSON.stringify({passed:errors.length===0&&external.length===0,base:'http://127.0.0.1:8004',database:'.tools/phase4/demo.db',browser:'Microsoft Edge headless via bundled Playwright',mocked:false,baseline,health,config,errors,external_requests:external,checks:['growth 600 to 900 and visit 12 to 20','visits 2400','saved and survives reload','A/B calculator','rain SR-001 risk 47.15','four plans','rules explanation','simulation']},null,2));
 await browser.close();console.log('Phase-four demo rehearsal passed');
})().catch(e=>{console.error(e);process.exit(1)});
